"""Dataset utilities for ISIC and PH2 skin lesion datasets."""
import logging
import random
from pathlib import Path
from typing import List, Optional, Tuple

import pandas as pd

logger = logging.getLogger(__name__)

# (image_path, lesion_size_mm, target_label, seg_path_or_None)
# seg_path_or_None é None no modo "model" (U-Net) e o caminho da máscara no modo "precomputed"
ImageEntry = Tuple[str, float, int, Optional[str]]


class SkinLesionDataset:
    """Loads and manages the ISIC skin lesion dataset from a metadata CSV.

    Cada linha do CSV deve ter ao menos: isic_id, target, clin_size_long_diam_mm.
    As imagens devem estar no formato {isic_id}.jpg dentro de image_dir.
    Retorna seg_path=None — a segmentação é gerada em tempo de execução pelo U-Net.
    """

    def __init__(self, metadata_csv: str, image_dir: str, random_seed: int = 42):
        """
        Args:
            metadata_csv: Path to the sample-metadata.csv file.
            image_dir: Directory containing ISIC .jpg images.
            random_seed: Seed for reproducible shuffling.
        """
        self.image_dir = Path(image_dir)
        self.random_seed = random_seed
        self.df = pd.read_csv(metadata_csv)
        logger.info("Loaded metadata CSV: %d entries from %s", len(self.df), metadata_csv)

    def get_image_paths(self, max_images: int = 0, balanced: bool = False) -> List[ImageEntry]:
        """Returns a shuffled list of ImageEntry tuples.

        Args:
            max_images: Maximum number of images to return. 0 = return all.
            balanced: If True, return equal numbers of class-0 and class-1 samples.
                      When combined with max_images, takes max_images//2 per class
                      (capped by the minority class size).

        Returns:
            List of (image_path, lesion_size_mm, target_label, None).
            seg_path is None because segmentation will be generated by the U-Net.
        """
        shuffled = self.df.sample(frac=1, random_state=self.random_seed).reset_index(drop=True)

        if balanced:
            class_0 = shuffled[shuffled["target"] == 0]
            class_1 = shuffled[shuffled["target"] == 1]
            n = min(
                max_images // 2 if max_images > 0 else len(class_0),
                len(class_0),
                len(class_1),
            )
            shuffled = pd.concat([class_0.iloc[:n], class_1.iloc[:n]])
            shuffled = shuffled.sample(frac=1, random_state=self.random_seed).reset_index(drop=True)
            logger.info("Balanced ISIC sample: %d class-0 + %d class-1 = %d total", n, n, len(shuffled))
        elif max_images > 0:
            shuffled = shuffled.iloc[:max_images]

        results = []
        for _, row in shuffled.iterrows():
            img_path = str(self.image_dir / f"{row['isic_id']}.jpg")
            lesion_size = float(row.get("clin_size_long_diam_mm", 0.0))
            target = int(row.get("target", -1))
            results.append((img_path, lesion_size, target, None))

        logger.info("Returning %d ISIC entries (max_images=%d, balanced=%s)", len(results), max_images, balanced)
        return results

    def get_lesion_size(self, isic_id: str) -> float:
        """Returns the longest clinical diameter (mm) for a given ISIC ID."""
        row = self.df[self.df["isic_id"] == isic_id]
        if row.empty:
            return 0.0
        return float(row["clin_size_long_diam_mm"].values[0])

    def get_target(self, isic_id: str) -> int:
        """Returns the binary target label (0=benign, 1=malignant) for a given ISIC ID."""
        row = self.df[self.df["isic_id"] == isic_id]
        if row.empty:
            return -1
        return int(row["target"].values[0])

    def __len__(self) -> int:
        return len(self.df)


class PH2Dataset:
    """Loads the PH2 dermoscopy dataset from its directory structure.

    Estrutura esperada por caso (NAME = e.g. "IMD002"):
        {dataset_dir}/{NAME}/{NAME}_Dermoscopic_Image/{NAME}.bmp  ← imagem original
        {dataset_dir}/{NAME}/{NAME}_lesion/{NAME}_lesion.bmp      ← máscara binária

    Retorna seg_path apontando para a máscara pré-computada — não é necessário U-Net.
    Se metadata_txt for fornecido, o target é extraído de "Histological Diagnosis":
      1 = contém "melanoma" (case-insensitive), 0 = demais casos.
    """

    def __init__(
        self,
        dataset_dir: str,
        random_seed: int = 42,
        metadata_txt: Optional[str] = None,
    ):
        """
        Args:
            dataset_dir: Raiz do dataset PH2, e.g. "PH2 Dataset images".
            random_seed: Seed para shuffle reprodutível.
            metadata_txt: Caminho para PH2_dataset.txt (pipe-delimited). Opcional;
                          sem ele, target=-1 para todos os casos.
        """
        self.dataset_dir = Path(dataset_dir)
        self.random_seed = random_seed
        self._targets: dict = self._load_metadata(metadata_txt) if metadata_txt else {}
        self.cases = self._discover_cases()
        logger.info("Found %d PH2 cases in %s", len(self.cases), dataset_dir)

    def _load_metadata(self, metadata_txt: str) -> dict:
        """Parses PH2_dataset.txt and returns {case_name: target} mapping.

        target=1 when Histological Diagnosis contains "melanoma" (case-insensitive),
        target=0 for all other cases (empty, nevus, dysplastic, etc.).
        """
        targets: dict = {}
        with open(metadata_txt, "r", encoding="utf-8") as f:
            for i, line in enumerate(f):
                if i == 0:
                    continue  # skip header
                parts = [p.strip() for p in line.split("||")]
                if len(parts) < 3:
                    continue
                name = parts[1]
                hist_diag = parts[2]
                if not name:
                    continue
                targets[name] = 1 if "melanoma" in hist_diag.lower() else 0
        logger.info("Loaded PH2 metadata: %d entries from %s", len(targets), metadata_txt)
        return targets

    def _discover_cases(self) -> List[str]:
        """Varre o diretório raiz e retorna todos os nomes de casos válidos.

        Um caso é válido se tiver tanto a imagem dermoscópica quanto a máscara de lesão.
        """
        valid = []
        for d in sorted(self.dataset_dir.iterdir()):
            if not d.is_dir():
                continue
            name = d.name
            img = d / f"{name}_Dermoscopic_Image" / f"{name}.bmp"
            mask = d / f"{name}_lesion" / f"{name}_lesion.bmp"
            if img.exists() and mask.exists():
                valid.append(name)
            else:
                logger.warning("Caso incompleto ignorado: %s", name)
        return valid

    def get_image_paths(self, max_images: int = 0, balanced: bool = False) -> List[ImageEntry]:
        """Returns a shuffled list of ImageEntry tuples.

        Args:
            max_images: Maximum number of images to return. 0 = return all.
            balanced: If True, return equal numbers of class-0 and class-1 samples.
                      Cases with target=-1 (unknown) are excluded from both pools.
                      When combined with max_images, takes max_images//2 per class
                      (capped by the minority class size).

        Returns:
            List of (image_path, lesion_size_mm, target_label, seg_path).
            seg_path aponta para a máscara binária pré-computada do dataset.
        """
        rng = random.Random(self.random_seed)
        shuffled = self.cases.copy()
        rng.shuffle(shuffled)

        if balanced:
            class_0 = [name for name in shuffled if self._targets.get(name, -1) == 0]
            class_1 = [name for name in shuffled if self._targets.get(name, -1) == 1]
            n = min(
                max_images // 2 if max_images > 0 else len(class_0),
                len(class_0),
                len(class_1),
            )
            shuffled = class_0[:n] + class_1[:n]
            rng.shuffle(shuffled)
            logger.info("Balanced PH2 sample: %d class-0 + %d class-1 = %d total", n, n, len(shuffled))
        elif max_images > 0:
            shuffled = shuffled[:max_images]

        results = []
        for name in shuffled:
            img_path = str(
                self.dataset_dir / name / f"{name}_Dermoscopic_Image" / f"{name}.bmp"
            )
            seg_path = str(
                self.dataset_dir / name / f"{name}_lesion" / f"{name}_lesion.bmp"
            )
            target = self._targets.get(name, -1)
            results.append((img_path, 0.0, target, seg_path))

        logger.info("Returning %d PH2 entries (max_images=%d, balanced=%s)", len(results), max_images, balanced)
        return results

    def __len__(self) -> int:
        return len(self.cases)
